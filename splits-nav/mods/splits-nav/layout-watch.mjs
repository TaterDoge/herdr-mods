// Register the layout repair as an on-demand job in the current user's session.
import { createHash } from 'node:crypto';
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, lstatSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';

const action = process.argv[2];
const appDir = resolve(process.env.HERDR_APP_HOME || join(homedir(), '.config/herdr-app'));
const worker = join(appDir, 'mods/splits-nav/layout-sync.mjs');
// launchd runs with its own PATH. Prefer the node the user actually invokes so
// a mise version bump does not silently break the job; process.execPath is the
// versioned path that disappears on upgrade.
function nodeExecutable() {
  const found = spawnSync('/usr/bin/which', ['node'], { encoding: 'utf8' });
  const path = found.status === 0 ? found.stdout.trim() : '';
  return path || process.execPath;
}
const argv = [nodeExecutable(), worker, appDir];
const paths = [join(appDir, 'layouts'), join(appDir, 'installed.json')];
const id = 'dev.herdr.splits-nav.layouts.' + createHash('sha256').update(appDir).digest('hex').slice(0, 12);
const marker = 'Generated by splits-nav layout-watch';
const watchMarker = join(appDir, '.splits-nav.layout-watch');

function previous(file) {
  const stat = lstatSync(file, { throwIfNoEntry: false });
  if (!stat) return null;
  if (stat.isFile()) {
    const text = readFileSync(file, 'utf8');
    if (text.includes(marker)) return text;
  }
  throw new Error(`Existing file is not managed by splits-nav: ${file}`);
}

function save(file, text, old) {
  if (old === text) return;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text, { mode: 0o600, flag: old === null ? 'wx' : 'w' });
}

function launchd() {
  const file = join(homedir(), 'Library/LaunchAgents', id + '.plist');
  const old = previous(file);
  const domain = `gui/${process.getuid()}`;
  const target = `${domain}/${id}`;
  const ctl = (...args) => execFileSync('launchctl', args, { stdio: 'inherit' });
  const loaded = spawnSync('launchctl', ['print', target], { stdio: 'ignore' }).status === 0;
  if (action === 'uninstall') {
    if (loaded) ctl('bootout', target);
    if (old !== null) unlinkSync(file);
    return;
  }
  const job = { Label: id, ProgramArguments: argv, RunAtLoad: true, WatchPaths: paths, ThrottleInterval: 1 };
  const logs = join(homedir(), 'Library/Logs/herdr-layout-watch');
  mkdirSync(logs, { recursive: true });
  job.StandardOutPath = join(logs, id + '.out.log');
  job.StandardErrorPath = join(logs, id + '.err.log');
  const xml = execFileSync('/usr/bin/plutil', ['-convert', 'xml1', '-o', '-', '-'], {
    input: JSON.stringify(job), encoding: 'utf8',
  }).replace('<plist version="1.0">', `<!-- ${marker} -->\n<plist version="1.0">`);
  save(file, xml, old);
  if (loaded && old === xml) return;
  if (loaded) ctl('bootout', target);
  ctl('bootstrap', domain, file);
}

function systemd() {
  const dir = join(process.env.XDG_CONFIG_HOME || join(homedir(), '.config'), 'systemd/user');
  const units = [id + '.service', id + '.path'];
  const [service, path] = units.map(unit => join(dir, unit));
  const [oldService, oldPath] = [previous(service), previous(path)];
  const ctl = (...args) => execFileSync('systemctl', ['--user', ...args], { stdio: 'inherit' });
  if (action === 'uninstall') {
    const installed = units.filter((_, i) => [oldService, oldPath][i] !== null);
    if (installed.length) {
      ctl('disable', '--now', ...installed);
      for (const unit of installed) unlinkSync(join(dir, unit));
      ctl('daemon-reload');
    }
    return;
  }
  if (argv.some(arg => /[\r\n]/.test(arg))) throw new Error('systemd unit paths must be single lines');
  const spec = value => value.replaceAll('%', '%%');
  const command = argv.map(arg => JSON.stringify(spec(arg).replaceAll('$', () => '$$'))).join(' ');
  const header = `# ${marker}\n[Unit]\nDescription=Splits Nav layout mounts\n`;
  const install = '\n[Install]\nWantedBy=default.target\n';
  save(service, `${header}\n[Service]\nType=oneshot\nExecStart=${command}\n${install}`, oldService);
  save(path, `${header}\n[Path]\n${paths.map(p => 'PathChanged=' + spec(p)).join('\n')}\n${install}`, oldPath);
  ctl('daemon-reload');
  ctl('enable', '--now', ...units);
}

try {
  if (!['install', 'uninstall'].includes(action)) throw new Error('Usage: node layout-watch.mjs install|uninstall');
  if (action === 'install' && !existsSync(worker)) throw new Error(`Copy the mod to ${dirname(worker)} first`);
  if (process.platform === 'darwin') launchd();
  else if (process.platform === 'linux') systemd();
  else throw new Error('Layout watching needs macOS launchd or Linux systemd --user');
  if (action === 'install') writeFileSync(watchMarker, '', { mode: 0o600 });
  else { try { unlinkSync(watchMarker); } catch (error) { if (error.code !== 'ENOENT') throw error; } }
  console.log(`Layout watcher ${action === 'install' ? 'installed' : 'removed'} for ${appDir}`);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
